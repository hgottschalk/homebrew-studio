export function findBjcpStyleForRecipe(
  styleId?: string,
  styleName?: string
): BjcpStyleItem | undefined {
  if (styleId) {
    const byId = BJCP_STYLES_CATALOG.find((s) => s.id === styleId);
    if (byId) return byId;
  }
  if (!styleName) return undefined;
  const normalized = styleName.toLowerCase();
  return (
    BJCP_STYLES_CATALOG.find(
      (s) =>
        `${s.name} (${s.code})`.toLowerCase() === normalized ||
        s.name.toLowerCase() === normalized
    ) ||
    BJCP_STYLES_CATALOG.find((s) =>
      normalized.includes(`(${s.code.toLowerCase()})`)
    )
  );
}
